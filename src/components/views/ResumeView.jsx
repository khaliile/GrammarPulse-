import React, { useState } from 'react';
import { 
  FileText, 
  Sparkles, 
  Printer, 
  Copy, 
  Check, 
  Download, 
  Layers, 
  Award, 
  BookOpen 
} from 'lucide-react';
import { PRESENT_SIMPLE_DATA } from '../../data/presentSimpleData';
import { soundManager } from '../../utils/audio';

export default function ResumeView({ tenseData, tenseMeta }) {
  const data = tenseData || PRESENT_SIMPLE_DATA;
  const meta = tenseMeta || data.meta;
  const resumeSummary = data.resumeSummary || PRESENT_SIMPLE_DATA.resumeSummary;
  const [copied, setCopied] = useState(false);

  const handlePrint = () => {
    soundManager.playClick();
    window.print();
  };

  const handleCopyMarkdown = () => {
    soundManager.playClick();
    const rows = (resumeSummary.formulaMatrix || []).map(r => `- **${r.form}**: \`${r.formula}\` (Ex: ${r.exampleI} / ${r.exampleHe}) - *${r.memoryAnchor}*`).join('\n');
    const md = `# ${meta.name} Executive Summary & Cheat-Sheet
Level: ${meta.level} | Aspect: ${meta.aspect} | Auxiliary: ${meta.auxiliary}

## 1. Master Formula Matrix
${rows}

## 2. Key Rule / Anchor
- Signal Words: ${(data.overview?.signalWords || []).join(', ')}
- Core Equation: ${resumeSummary.adverbGoldenFormula || 'Subject + Auxiliary + Main Verb'}

Generated by English Mastery Studio
`;

    navigator.clipboard.writeText(md).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    });
  };

  return (
    <div className="content-max-width">
      {/* Header */}
      <div className="section-hero">
        <div style={{ display: 'flex', alignItems: 'flex-start', justifyContent: 'space-between', flexWrap: 'wrap', gap: '16px' }}>
          <div>
            <span className="section-tag" style={{ borderColor: meta.accentColor }}>
              <Sparkles size={14} /> {meta.name} • Module 07: Executive Synthesis
            </span>
            <h2>{resumeSummary.title}</h2>
            <p>{resumeSummary.subtitle}</p>
          </div>

          <div style={{ display: 'flex', gap: '10px' }}>
            <button className="btn-secondary" onClick={handleCopyMarkdown}>
              {copied ? <Check size={16} color="var(--emerald-400)" /> : <Copy size={16} />}
              <span>{copied ? "Copied Markdown!" : "Copy Notes"}</span>
            </button>
            <button className="btn-primary" onClick={handlePrint}>
              <Printer size={16} />
              <span>Print / Save PDF</span>
            </button>
          </div>
        </div>
      </div>

      {/* Main Structural Matrix */}
      <div className="glass-card" style={{ padding: '32px', marginBottom: '28px', borderTop: '4px solid var(--indigo-500)' }}>
        <h3 style={{ fontSize: '1.25rem', marginBottom: '14px', display: 'flex', alignItems: 'center', gap: '8px' }}>
          <Layers size={20} color="var(--indigo-500)" />
          The Master Formula Matrix
        </h3>

        <table className="resume-table">
          <thead>
            <tr>
              <th>Sentence Form</th>
              <th>Syntactic Formula</th>
              <th>I / You / We / They</th>
              <th>He / She / It</th>
              <th>Memory Anchor</th>
            </tr>
          </thead>
          <tbody>
            {resumeSummary.formulaMatrix.map((item, idx) => (
              <tr key={idx}>
                <td style={{ fontWeight: '700', color: 'var(--text-main)' }}>{item.form}</td>
                <td style={{ fontFamily: 'var(--font-mono)', fontWeight: '700', color: 'var(--cyan-400)' }}>{item.formula}</td>
                <td style={{ color: 'var(--text-secondary)' }}>{item.exampleI}</td>
                <td style={{ color: 'var(--emerald-400)', fontWeight: '600' }}>{item.exampleHe}</td>
                <td style={{ fontSize: '0.82rem', color: 'var(--amber-400)' }}>{item.memoryAnchor}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {/* Spelling Rules Quick Cards */}
      <div className="glass-card" style={{ padding: '32px', marginBottom: '28px' }}>
        <h3 style={{ fontSize: '1.25rem', marginBottom: '16px' }}>3rd Person Singular Spelling Reference</h3>
        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(220px, 1fr))', gap: '14px' }}>
          {resumeSummary.spellingPills.map((pill, idx) => (
            <div key={idx} style={{ background: 'var(--bg-input)', padding: '16px', borderRadius: 'var(--radius-md)', border: '1px solid var(--border-subtle)' }}>
              <span style={{ fontSize: '0.75rem', fontWeight: '700', textTransform: 'uppercase', color: 'var(--indigo-500)', display: 'block', marginBottom: '4px' }}>
                {pill.ending}
              </span>
              <div style={{ fontFamily: 'var(--font-mono)', fontSize: '1.2rem', fontWeight: '800', color: 'var(--emerald-400)', marginBottom: '6px' }}>
                {pill.change}
              </div>
              <div style={{ fontSize: '0.85rem', color: 'var(--text-secondary)' }}>
                {pill.example}
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Frequency Formula & Traps Recap */}
      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(320px, 1fr))', gap: '20px', marginBottom: '32px' }}>
        <div className="glass-card">
          <h4 style={{ fontSize: '1.1rem', marginBottom: '10px' }}>Adverb Placement Golden Equation</h4>
          <div style={{ background: 'var(--bg-input)', padding: '16px', borderRadius: 'var(--radius-md)', fontFamily: 'var(--font-mono)', color: 'var(--amber-400)', fontWeight: '700', fontSize: '0.92rem', marginBottom: '12px' }}>
            {resumeSummary.adverbGoldenFormula}
          </div>
          <p style={{ fontSize: '0.85rem' }}>
            Put the frequency adverb directly BEFORE normal verbs ("always drinks") and immediately AFTER 'to be' ("is always").
          </p>
        </div>

        <div className="glass-card">
          <h4 style={{ fontSize: '1.1rem', marginBottom: '10px' }}>Exam Safeguard Checklist</h4>
          <ul style={{ paddingLeft: '18px', display: 'flex', flexDirection: 'column', gap: '6px', fontSize: '0.88rem' }}>
            <li>Did you put '-s' on He/She/It in positive sentences?</li>
            <li>Did you remove the '-s' after 'doesn't'?</li>
            <li>Did you avoid 'do/does' with the verb 'to be'?</li>
            <li>Did you avoid '-ing' on stative verbs like 'know', 'want'?</li>
          </ul>
        </div>
      </div>
    </div>
  );
}
